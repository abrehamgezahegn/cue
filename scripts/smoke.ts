import assert from 'node:assert/strict';
import { token, port } from '../server/config';
import { demoTranscript } from '../src/panel/demo';
const base = `http://127.0.0.1:${port}`;
const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' };
const health = await fetch(base + '/api/health', { headers }).then(r => r.json());
assert.equal(health.configured, true);
console.log('DeepInfra key is configured. Model:', health.model);
assert.equal((await fetch(base + '/api/health')).status, 401);
assert.equal((await fetch(base + '/api/health', { headers: { ...headers, Origin: 'https://untrusted.example' } })).status, 403);
assert.equal((await fetch(base + '/.env.local')).status, 404);
console.log('Local API rejects unauthenticated and foreign-origin requests. Environment file is not served.');
const response = await fetch(base + '/api/ask', { method: 'POST', headers, body: JSON.stringify({ question: 'How should I deal with my phone during focused work?', segments: demoTranscript.segments, history: [] }) });
const answer: any = await response.json();
if (!response.ok) throw new Error(answer.error);
assert.equal(answer.notFound, false);
assert.ok(answer.parts.some((p: any) => p.citations.some((c: any) => c.start === 134)));
console.log('Live DeepInfra answer:', answer.parts.map((p: any) => p.text).join(' '));
console.log('Verified source timestamp: 2:14.');
const captions = await fetch(base + '/api/transcript', { method: 'POST', headers, body: JSON.stringify({ videoId: 'jNQXAC9IVRw' }) });
const transcript: any = await captions.json();
console.log(captions.ok ? `Live ytdl retrieved ${transcript.segments.length} segments.` : 'Live ytdl was unavailable for the test video. Browser fallback is required.');
